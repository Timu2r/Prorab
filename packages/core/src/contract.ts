import { BRAND } from "./brand";
import { formatRub, type Kopecks } from "./money";

/**
 * Договор подряда с клиентом (docs/KALKULYATOR.md, раздел 6). Текст один для сайта и приложения, данные
 * подставляются из заявки. Меняете условия — поднимите CONTRACT_VERSION: у каждого заключённого договора
 * записано, по какой версии текста он заключён. Копия для чтения — dogovory/02-dogovor-s-klientom.md.
 */
export const CONTRACT_VERSION = "2026-09-26";

export const CONTRACT_METHODS = ["online", "phone", "paper"] as const;
export type ContractMethod = (typeof CONTRACT_METHODS)[number];

export const CONTRACT_METHOD_LABELS: Record<ContractMethod, string> = {
  online: "онлайн: смета согласована в личном кабинете",
  phone: "по телефону: клиент согласился, владелец отметил в приложении",
  paper: "лично: подписан на бумаге при встрече с прорабом",
};

export type ContractData = {
  number: string;
  /** Дата заключения. null — шаблон или договор ещё не заключён. */
  date: string | Date | null;
  client: { name: string; phone: string; companyName?: string; inn?: string } | null;
  address: string;
  category: string;
  priceWork: Kopecks | null;
  priceGoods: Kopecks | null;
  method: ContractMethod | null;
};

export type ContractSection = { title: string; items: string[] };

export type ContractDocument = {
  title: string;
  place: string;
  preamble: string;
  sections: ContractSection[];
  contractor: string[];
  customer: string[];
  accepted: string | null;
};

const BLANK = "__________";

function day(v: string | Date): string {
  const d = new Date(new Date(v).getTime() + 3 * 3_600_000); // по Москве
  return `${String(d.getUTCDate()).padStart(2, "0")}.${String(d.getUTCMonth() + 1).padStart(2, "0")}.${d.getUTCFullYear()}`;
}

function time(v: string | Date): string {
  const d = new Date(new Date(v).getTime() + 3 * 3_600_000);
  return `${String(d.getUTCHours()).padStart(2, "0")}:${String(d.getUTCMinutes()).padStart(2, "0")}`;
}

